// последнего шага. DONE - остановился, WAIT - ждём, FALLBACK - остановить
// частотой 0 (только на стадии 1), FAIL - не остановился, блокировка.
enum STOP_CHECK : uint8_t { STOPCHK_DONE, STOPCHK_WAIT, STOPCHK_FALLBACK, STOPCHK_FAIL };
