/*
 * Алгоритм «Гибрид» регулирования перегрева ЭРВ - чистая арифметика, без HP и без Arduino.
 *
 * ЗАЧЕМ ОТДЕЛЬНО. Так же, как у OverheatCalc: тест, реплей по логам и симулятор линкуются с настоящим кодом,
 * а не с его копией. Ошибка здесь тихая - вентиль едет не туда, а видно это только на работающем ТН.
 *
 * ЧТО ДЕЛАЕТ. Раз в период (eev.time) считает, на сколько шагов сдвинуть вентиль:
 *   s   = перегрев - цель, K                      (s > 0: перегрев выше цели, вентиль открывать)
 *   dx  = Kc * ((s - s_пред) + период / Ti * s)    скоростной ПИ, ограничен +-stepMax
 *   если частота компрессора есть (обе, прошлая и текущая, выше 1 Гц):
 *   dx += kff * x * (f / f_пред - 1)               прямая подача вслед за частотой, ограничена +-ffMax
 *   если перегрев < ohMin и с пуска прошло не меньше protDelay: dx -= 1 + (ohMin - перегрев) / 0,5 K
 *   acc += dx; шаг = целая часть acc; acc -= шаг   дробные шаги копятся, а не теряются
 * Итог - новое положение, ограниченное minSteps ... maxSteps. Вентиль сюда не двигается: это делает devEEV.
 *
 * ЕДИНИЦЫ. Целочисленная арифметика, результат не зависит от платформы и воспроизводим в тестах:
 *   перегрев и цель - сотые градуса; Kc, kff, ohMin - сотые доли; частота - сотые герца;
 *   накопитель - тысячные доли шага; Ti, период, protDelay - секунды.
 * Промежуточные произведения считаются в int64: Kc * (ds * Ti + период * s) не помещается в int32.
 *
 * ЗАЩИТНЫЕ ПРАВИЛА (поля настроек приходят из EEPROM и из веба, им верить нельзя):
 *   Ti < 1 считается за 1; stepMax <= 0 - значение по умолчанию 45; ffMax <= 0 или kff <= 0 отключают подачу;
 *   maxSteps < minSteps - положение не меняется; итоговый сдвиг за период ограничен stepMax + ffMax + 5 шагов.
 */
#ifndef EEVHybrid_h
#define EEVHybrid_h

#include <stdint.h>

#define EEVHYB_STEP_MAX_DEFAULT	45		// stepMax = 0 (в настройках «без ограничения»): предел сдвига ПИ-части за период, шагов
#define EEVHYB_PROT_DELAY		120		// защита от низкого перегрева включается через столько секунд после пуска компрессора
#define EEVHYB_FREQ_MIN			100		// частота не выше 1 Гц (сотые герца) - подача по частоте отключена

struct EevHybridParams
{
	int16_t  Kc100;			// усиление, шагов на 1 K, сотые доли (300 = 3,00)
	uint16_t Ti;			// время интегрирования, с
	int16_t  ohMin100;		// нижняя граница перегрева для защиты, сотые градуса; 0 - защита выключена
	int16_t  kff100;		// доля прямой подачи по частоте, сотые доли (100 = 1,00); 0 - подача выключена
	int16_t  ffMax;			// предел прямой подачи за период, шагов
	int16_t  target100;		// цель перегрева, сотые градуса
	uint16_t period;		// период расчёта (eev.time), с
	int16_t  stepMax;		// предел сдвига ПИ-части за период, шагов (pid_max); 0 - EEVHYB_STEP_MAX_DEFAULT
	int16_t  minSteps;		// границы положения вентиля, шагов
	int16_t  maxSteps;
	uint16_t protDelay;		// задержка защиты после пуска, с (EEVHYB_PROT_DELAY)
};

struct EevHybridState
{
	int32_t acc1000;		// накопленная дробная часть шага, тысячные доли
	int32_t sPrev100;		// прошлое отклонение перегрева от цели, сотые градуса (int32: разность двух int16 не помещается в int16)
	int16_t fPrev100;		// прошлая частота компрессора, сотые герца
};

// Сброс при пуске компрессора, возобновлении после паузы и смене алгоритма: накопитель в ноль,
// «прошлые» значения - текущие, поэтому первый период не даёт ни скачка по производной, ни подачи по частоте.
void    eevhyb_reset(EevHybridState *st, const EevHybridParams *p, int16_t overheat100, int16_t freq100);

// Один период расчёта. x - текущее положение вентиля, secSinceStart - секунд с пуска компрессора.
// Возвращает ограниченное положение; requested при ненулевом указателе получает положение до ограничения (для защит).
int16_t eevhyb_step(EevHybridState *st, const EevHybridParams *p, int16_t overheat100, int16_t freq100, int16_t x, uint32_t secSinceStart, int32_t *requested = 0);


// ---------------------------------------------------------------------------
// Настройки гибрида и стартовая позиция по частоте. Здесь же, чтобы значения по умолчанию, расчёт позиции и перенос флагов
// проверялись на хосте: Hardware.h с devEEV на хосте не собирается.
// ---------------------------------------------------------------------------

// Биты флагов ЭРВ (type_settingsEEV.flags). Бит 10 - прежнее «прямое управление», удалено: в старых файлах он может
// быть установлен, поэтому НЕ ПЕРЕИСПОЛЬЗУЕТСЯ и при чтении версии ниже 151 сбрасывается.
#define EEV_FLAGBIT_DIRECT_OLD	10
#define EEV_FLAGBIT_HYBRID		11		// алгоритм «Гибрид» (иначе ПИД)
#define EEV_FLAGBIT_STARTFREQ	12		// стартовая позиция по стартовой частоте инвертора
#define EEV_SETTINGS_VER_HYBRID	151		// с этой версии формата сохранения поля гибрида и старта по частоте записаны

// Часть настроек ЭРВ, которую занимает гибрид (в EEPROM лежит в полях, освободившихся после прямого управления)
struct EevHybCfg
{
	int16_t  Kc100;			// усиление, шагов на 1 K, сотые доли
	uint16_t Ti;			// время интегрирования, с
	int16_t  ohMin100;		// защита от низкого перегрева, сотые градуса
	int16_t  kff100;		// подача по частоте, сотые доли
	int16_t  ffMax;			// предел подачи за период, шагов
	int16_t  sphz100;		// старт по частоте: шагов на герц, отопление и охлаждение, сотые доли
	int16_t  sphzb100;		// то же для ГВС
};

// Значения по умолчанию (для хода 480 шагов); усиление, предел подачи и коэффициенты старта масштабируются по maxSteps / 480
// и ограничиваются границами реестра; время и доли от клапана не зависят. maxSteps <= 0 - как для 480.
void    eevhyb_default_cfg(EevHybCfg *c, int16_t maxSteps);

// Стартовая позиция по частоте: sphz100 * freq100 / 10000, округление, в границах minSteps ... maxSteps
// (границы перепутаны - minSteps). sphz100 - шагов на герц в сотых, freq100 - стартовая частота в сотых герца.
int16_t eevhyb_start_pos(int16_t sphz100, int16_t freq100, int16_t minSteps, int16_t maxSteps);

// Чтение настроек версии ниже 151: биты 10-12 сбрасываются (10 - прежнее прямое управление, 11-12 в таких файлах
// не существовали), остальные флаги не трогаются.
uint16_t eevhyb_migrate_flags(uint8_t savedVer, uint16_t flags);

// true - в настройках этой версии полей гибрида нет, нужны значения по умолчанию
bool    eevhyb_cfg_needs_defaults(uint8_t savedVer);

#endif
