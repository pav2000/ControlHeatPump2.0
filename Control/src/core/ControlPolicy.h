// ---- Сторож сетевого чипа W5500 ----
// Чип дважды замолкал (ping и ARP не отвечали) при живом PHY: светодиоды линка мигали, а проверка «бит LINK раз в минуту» ничего не
// видела. Теперь раз в NETCHIP_TEST_S секунд читаются регистры чипа и сверяются со снимком, снятым сразу после успешной инициализации
// (initW5200). Расхождение - сброс и инициализация заново. Решения - чистые функции, проверяются на хосте (tests/test_errorcodes.cpp).
struct NetChipRegs {
	uint8_t version;      // VERSIONR: у W5500 всегда 4; 0x00/0xFF - чип не отвечает или шина мусорит
	uint8_t mode;         // MR
	uint8_t phy;          // PHYCFGR, бит 0 - линк
	uint8_t mac[6];       // SHAR
	uint8_t ip[4];        // SIPR
	uint8_t gw[4];        // GAR
	uint8_t mask[4];      // SUBR
};
enum NETCHIP_FAULT : uint8_t {
	NCF_NONE = 0, // Отклонения отсутствуют.
	NCF_VERSION,          // версия не та: чип не отвечает или чтение испорчено
	NCF_MODE,             // регистр режима изменился
	NCF_MAC,              // MAC не тот
	NCF_IP,               // IP не тот (в том числе 0.0.0.0 после сброса чипа в значения по умолчанию)
	NCF_GATEWAY, // Изменился адрес шлюза.
	NCF_MASK, // Изменилась маска подсети.
	NCF_LINK,             // нет линка (кабель)
	NCF_NOINIT,           // чип ещё ни разу не был успешно инициализирован (снимка нет)
	NCF_PING              // не прошёл ping внешнего хоста (4 попытки подряд уже были): подтверждён сразу
};
#define NETCHIP_TEST_S     10     // период самотеста, секунд
#define NETCHIP_FAILS      2      // расхождений подряд до сброса (кроме NCF_PING)
#define NETCHIP_MIN_GAP_S  30     // не чаще одного сброса за это время
#define NETCHIP_MANY       5      // столько сбросов за NETCHIP_WINDOW_S - «много»: однократное уведомление, пауза растёт
#define NETCHIP_SLOW_GAP_S 300    // пауза между сбросами, когда их «много»
#define NETCHIP_WINDOW_S   3600 // Окно подсчёта восстановлений, с.
// Первое расхождение с базой по приоритету (VERSION > MODE > MAC > IP > GATEWAY > MASK > LINK), NCF_NONE - всё сошлось.
NETCHIP_FAULT NetChip_Check(const NetChipRegs &got, const NetChipRegs &base);
struct NetChipWatch {
	uint8_t  fails;           // расхождений подряд
	uint8_t  recoveries;      // сбросов в текущем окне
	bool     warned;          // уведомление в этом окне уже было
	bool     ever;            // сброс уже был
	uint32_t last_recover_s;  // момент последнего сброса
	uint32_t window_start_s;  // начало окна подсчёта сбросов
};
enum NETCHIP_ACTION : uint8_t {
	NCA_NONE,          // Восстановление пока не требуется.
	NCA_RECOVER,       // Переинициализировать чип.
	NCA_RECOVER_NOTIFY // Переинициализировать чип и предупредить о серии отказов.
};
// Сбрасывает состояние наблюдателя w. Значение не возвращает.
static inline void NetChip_Init(NetChipWatch *w) { w->fails = 0; w->recoveries = 0; w->warned = false; w->ever = false; w->last_recover_s = 0; w->window_start_s = 0; }
// Решение по результату очередного замера. now_s - любые монотонные секунды. NCA_RECOVER_NOTIFY - сброс И однократное уведомление «сбросов слишком много».
NETCHIP_ACTION NetChip_Decide(NetChipWatch *w, NETCHIP_FAULT fault, uint32_t now_s);

// ---- Состояние контроллера SPI0 ----
// SPI0 общий у W5500 (свой драйвер с DMA), SD (SdFat) и флеша (SerialFlash через библиотеку Arduino SPI); все трое используют канал 3
// и переписывают его регистры (режим MR целиком у SdFat и W5500, CSR3 у всех): SdFat на каждый блок, флеш на каждую операцию (паузу
// DLYBCT, которую добавляет ядро, гасит сразу), W5500 перед каждым обменом (spiNetSelect). Проверка ловит случай, когда чья-то
// настройка увела SPI0 с общей конфигурации.
#define SPI_ANOM_MASTER   0x01   // MR: не ведущий
#define SPI_ANOM_VARIABLE 0x02   // MR: переменный выбор периферии (PS=1), драйвер W5500 пишет TDR без номера канала
#define SPI_ANOM_CHANNEL  0x04   // MR: выбран не канал 3
#define SPI_ANOM_MODE     0x08   // CSR3: не режим 0 (CPOL=1 или NCPHA=0)
#define SPI_ANOM_BITS     0x10   // CSR3: не 8 бит
#define SPI_ANOM_SCBR     0x20   // CSR3: делитель вне 2...8 (тактовая выше 42 МГц или ниже 10 МГц)
#define SPI_ANOM_DLYBCT   0x40   // CSR3: пауза между байтами (DLYBCT != 0, так настраивает ядро Arduino) - передача в 2-3 раза медленнее
uint8_t Spi0_Check(uint32_t mr, uint32_t csr3);

// Обнуление счётчика повторных пусков (num_repeat). Прежде он обнулялся только ручным
// пуском и перезагрузкой: за месяцы работы nStart разнесённых во времени эпизодических
// ошибок останавливали ТН насовсем. Теперь после REPEAT_RESET_S непрерывной работы
// (pWORK_HP) без ошибки счёт начинается заново. Время - монотонные тики, а не часы:
// NTP не сдвигает окно. Окно перезапускается любой ошибкой, выходом из работы и
// самим повтором. true - пора обнулить (окно при этом начинается заново).
#define REPEAT_RESET_S    3600 // Выдержка перед очисткой счётчика повторных пусков, с.
struct RepeatWatch {
	uint32_t since_ms; // Начало интервала работы без ошибок, монотонные миллисекунды.
};
bool Error_RepeatReset(RepeatWatch &w, uint8_t num_repeat, bool work_ok, uint32_t now_ms, uint32_t limit_ms);
// fails - сбоев подряд, since_ms - с последнего ответа, running - инвертор в работе.
// Потеря: сбоев не меньше max_fails ИЛИ молчание дольше max_ms_run (в работе)
// либо max_ms_idle (остановлен).
bool   Error_LinkLost(uint8_t fails, uint32_t since_ms, bool running,
                      uint8_t max_fails, uint32_t max_ms_run, uint32_t max_ms_idle);

// Что делать после критической ошибки
enum ERROR_ACTION : uint8_t {
	ERR_ACT_Stop,      // останов без попыток пуска
	ERR_ACT_Repeat,    // повторный пуск
};

/*
 * Решение о повторном пуске после ошибки.
 *
 * Режим приходит параметром, и обе ветки проходят тест: при сборке по умолчанию он
 * выключен и не собирается, поэтому через #ifdef проверить его было бы негде.
 *
 * stop_command_failed - команда аварийного останова не принята приводом
 * nStart      - разрешённое число повторных пусков, 0 - повторов нет
 * num_repeat  - сколько повторов уже сделано
 * no_restart  - включён режим NOT_RESTART_ON_CRITICAL_ERRORS
 * err         - код ошибки
 */
ERROR_ACTION Error_Decide(bool stop_command_failed, uint8_t nStart, uint8_t num_repeat,
                          bool no_restart, int8_t err);

// Перечисляемый тип - точка возврата из алгоритма управления (расшифровка состояния)
// Расшифровка кода (пример Bp12  Бойлер - Алгоритм ПИД - изменение частоты ПИДом)
// Код имеет три поля <источник><алгоритм><код_алгоритма>
// Источник: B-бойлер, H-отопление, C-охлаждение
// Алгоритм: h - гистерезис, p - ПИД
// Код алгоритма
// 1 - выключение по подаче
// 2 - включение по гистерезису
// 3 - выключение по гистерезису
// 4 - внутри гистерезиса (продолжение: нагрев или охлаждение)
// 5 - внутри гистерезиса пауза
// 6 - сброс частоты по подаче
// 7 - сброс частоты по мощности
// 8 - сброс частоты по температуре компрессора
// 9 - сброс частоты по давлению
// 10 - разгон, пид не работает
// 11 - время пида не пришло
// 12 - дошли до ПИДа, регулируем
// 13 - включение по обратке достигнута минимальная температура обратки
// 14 - работа супербойлера ПИД ГВС (заход в бойлер)
// 15 - Бойлер греется от предконденсатора (заход в отопление)
// 16 - сброс частоты по току инвертора
// 17 - блокировка роста частоты ПИДом при подходе к уровням защиты ПОДАЧА
// 18 - блокировка роста частоты ПИДом при подходе к уровням защиты МОЩНОСТЬ
// 19 - блокировка роста частоты ПИДом при подходе к уровням защиты ТОК
// 20 - блокировка роста частоты ПИДом при подходе к уровням защиты TCOMP
// 21 - блокировка роста частоты ПИДом при подходе к уровням защиты ДАВЛЕНИЮ
// 22 - Выключение нагрева бойлера ТН для перехода в режим ДОГРЕВА его ТЭНом
// 23 - Выключение режима ТН при достижении уровня защиты по подаче (достижение границы)
// 24 - Выключение режима ТН при достижении уровня защиты по мощности (достижение границы)
// 25 - Выключение режима ТН при достижении уровня защиты по температуре компрессора (достижение границы)
// 26 - Выключение режима ТН при достижении уровня защиты по давлению (достижение границы)
