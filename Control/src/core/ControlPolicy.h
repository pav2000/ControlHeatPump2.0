// Контроль остановки инвертора после снятия команды ХОД (RCOMP). Решение по
// времени, как у потери связи: чистая функция, проверяется на хосте.
// running - инвертор в состоянии "вращение"/"толчковый ход"; stage - 1 после
// снятия RCOMP, 2 после попытки остановить частотой 0; since_ms - время с
// последнего шага. DONE - остановился, WAIT - ждём, FALLBACK - остановить
// частотой 0 (только на стадии 1), FAIL - не остановился, блокировка.
enum STOP_CHECK : uint8_t {
	STOPCHK_DONE,     // Инвертор остановился.
	STOPCHK_WAIT,     // Продолжить ожидание.
	STOPCHK_FALLBACK, // Попытаться остановить заданием нулевой частоты.
	STOPCHK_FAIL      // Резервный останов не подтверждён.
};
STOP_CHECK Error_StopCheck(bool running, uint8_t stage, uint32_t since_ms,
                           uint32_t wait_ms, uint32_t fallback_ms);
// Ожидание остановки инвертора при старте контроллера (initFC: после сброса на
// работающем компрессоре инвертор ещё вращается). Раньше ждали вечно: при обрыве
// связи get_readState блокирует инвертор и state навсегда ERR_LINK_FC, а аппаратный
// вачдог уже работает - перезагрузки по кругу. stopped - состояние "остановка" или
// "остановка с выбегом"; lost - связи нет или инвертор заблокирован; elapsed_ms -
// с начала ожидания. Остановка важнее предела: инвертор, вставший на последнем
// опросе, ошибкой не считается.
enum INIT_STOP : uint8_t {
	INITSTOP_DONE, // Останов подтверждён.
	INITSTOP_WAIT, // Продолжить опрос.
	INITSTOP_FAIL  // Потеря связи или истечение ожидания останова.
};
INIT_STOP Error_InitStopWait(bool stopped, bool lost, uint32_t elapsed_ms, uint32_t limit_ms);

